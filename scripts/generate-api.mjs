import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
const root = fileURLToPath(new URL('../', import.meta.url));
const executable = process.env.XFOLD_BINARY || `${root}target/debug/xfold${process.platform === 'win32' ? '.exe' : ''}`;
const result = spawnSync(executable, ['openapi'], { encoding: 'utf8' });
if (result.status !== 0) throw new Error(result.error?.message || result.stderr);
const schema = JSON.parse(result.stdout);
mkdirSync(`${root}docs`, { recursive: true });
writeFileSync(`${root}docs/openapi.json`, `${JSON.stringify(schema, null, 2)}\n`);
writeFileSync(`${root}web/src/schema.ts`, astToString(await openapiTS(schema)));
let client = `// Generated by scripts/generate-api.mjs from the backend OpenAPI contract.\nimport type { operations } from './schema';\n\nexport type RequestOptions = { signal?: AbortSignal; baseUrl?: string };\nasync function request<T>(path: string, method: string, body: unknown, options: RequestOptions): Promise<T> {\n  const response = await fetch((options.baseUrl || '') + path, { method, signal: options.signal, headers: body === undefined ? undefined : { 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });\n  const value = await response.json();\n  if (!response.ok) throw new Error(value.error || response.statusText);\n  return value;\n}\n\n`;
for (const [path, methods] of Object.entries(schema.paths)) {
  for (const [method, operation] of Object.entries(methods)) {
    const id = operation.operationId;
    if (!id || id === 'events') continue; // SSE has a native EventSource transport.
    const args = [];
    const names = (operation.parameters || []).filter(p => p.in === 'path').map(p => p.name);
    if (names.length) args.push(`path: operations['${id}']['parameters']['path']`);
    if (operation.requestBody) args.push(`body: operations['${id}']['requestBody']['content']['application/json']`);
    if (method === 'get') args.push(`query: operations['${id}']['parameters']['query'] = {}`);
    args.push('options: RequestOptions = {}');
    const template = path.replace(/\{(\w+)\}/g, (_, name) => '${encodeURIComponent(path.' + name + ')}');
    client += `export function ${id}(${args.join(', ')}): Promise<operations['${id}']['responses'][200]['content']['application/json']> {\n`;
    client += `  let url = \`${template}\`;\n`;
    if (method === 'get') client += `  const search = new URLSearchParams(Object.entries(query || {}).filter(([, v]) => v !== undefined).map(([k, v]) => [k, String(v)]));\n  if (search.size) url += '?' + search;\n`;
    client += `  return request(url, '${method.toUpperCase()}', ${operation.requestBody ? 'body' : 'undefined'}, options);\n}\n\n`;
  }
}
writeFileSync(`${root}web/src/generated-client.ts`, client);
console.log('Generated OpenAPI, TypeScript schemas, and operation client from Rust DTOs.');
